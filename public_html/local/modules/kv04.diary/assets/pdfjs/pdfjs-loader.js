// Единственный файл дневника на модульном синтаксисе. pdf.js с четвёртой
// версии поставляется только как ESM, а весь остальной наш код — обычные
// скрипты в стиле ES5. Шим стоит между ними: браузер грузит его как
// <script type="module">, а наружу выставляет привычный глобальный объект.
//
// Отдельным файлом, а не inline-скриптом: инлайн упёрся бы в CSP, случись ей
// появиться, и не давал бы кэшировать себя вместе с библиотекой.
//
// import здесь динамический, хотя статический был бы короче: в статическом не
// проставить метку версии, а без неё сервис-воркер положит pdf.js в кэш
// навсегда. Метку берём из собственного адреса — её уже проставил шаблон.
const version = new URL(import.meta.url).searchParams.get('v');
const src = './pdf.min.js' + (version ? '?v=' + encodeURIComponent(version) : '');

// Обещание, а не готовый объект: событие load у модульного скрипта случается
// раньше, чем доедет эта загрузка, и ждать надо именно её.
window.kv04PdfjsReady = import(src).then((pdfjsLib) => {
	window.pdfjsLib = pdfjsLib;
	return pdfjsLib;
});
